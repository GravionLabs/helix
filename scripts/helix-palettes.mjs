#!/usr/bin/env node
// Writes projects/core/themes/helix/palettes.ts: Aura's (Tailwind's) colour scales with
// their chroma reduced in OKLCH, lightness untouched. Helix's primary and severity
// colours are these muted scales (#521 review: the saturated Tailwind hues were too
// loud). Run: node scripts/helix-palettes.mjs [chroma factor, default 0.55]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const AURA = path.join(ROOT, 'projects/core/themes/aura/base/index.ts');
const OUT = path.join(ROOT, 'projects/core/themes/helix/palettes.ts');

/** The scales the component tokens reference (primary + severities + their tints). */
export const SCALES = ['indigo', 'red', 'green', 'emerald', 'yellow', 'amber', 'orange', 'sky', 'blue', 'purple'];
export const CHROMA = Number(process.argv[2] ?? 0.55);

// sRGB <-> OKLCH (Björn Ottosson's OKLab), enough for a build script.
const lin = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const gam = (c) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);
const clamp = (v) => Math.min(1, Math.max(0, v));

export function hexToOklch(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => lin(parseInt(hex.slice(i, i + 2), 16) / 255));
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s;
  const A = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s;
  const B = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s;
  return { L, C: Math.hypot(A, B), h: Math.atan2(B, A) };
}

export function oklchToHex({ L, C, h }) {
  const A = C * Math.cos(h);
  const B = C * Math.sin(h);
  const l = (L + 0.3963377774 * A + 0.2158037573 * B) ** 3;
  const m = (L - 0.1055613458 * A - 0.0638541728 * B) ** 3;
  const s = (L - 0.0894841775 * A - 1.291485548 * B) ** 3;
  const rgb = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
  return `#${rgb.map((c) => Math.round(clamp(gam(clamp(c))) * 255).toString(16).padStart(2, '0')).join('')}`;
}

/** A scale with its chroma scaled by `factor`; lightness and hue stay. */
export function mute(scale, factor = CHROMA) {
  return Object.fromEntries(
    Object.entries(scale).map(([step, hex]) => {
      const c = hexToOklch(hex);
      return [step, oklchToHex({ ...c, C: c.C * factor })];
    }),
  );
}

export function auraPrimitive(source = fs.readFileSync(AURA, 'utf8')) {
  const palettes = {};
  for (const [, name, body] of source.matchAll(/^\s+([a-z]+): \{ (50: '#[0-9a-f]{6}'.*?) \},?$/gm)) {
    palettes[name] = Object.fromEntries([...body.matchAll(/(\d+): '(#[0-9a-f]{6})'/g)].map(([, k, v]) => [k, v]));
  }
  return palettes;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const aura = auraPrimitive();
  const lines = [
    '// Generated by `node scripts/helix-palettes.mjs` — do not edit by hand.',
    `// Aura's colour scales with their OKLCH chroma × ${CHROMA}; lightness and hue unchanged.`,
    'import type { PaletteDesignToken } from \'@gravionlabs/helix-core/themes/types\';',
    '',
    'export const palettes = {',
  ];
  for (const name of SCALES) {
    if (!aura[name]) throw new Error(`no ${name} scale in Aura`);
    const muted = mute(aura[name]);
    lines.push(`    ${name}: { ${Object.entries(muted).map(([k, v]) => `${k}: '${v}'`).join(', ')} },`);
  }
  lines.push('} satisfies Record<string, PaletteDesignToken>;', '');
  fs.writeFileSync(OUT, lines.join('\n'));
  for (const name of SCALES) console.log(`${name.padEnd(8)} 500: ${aura[name][500]} → ${mute(aura[name])[500]}`);
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}
