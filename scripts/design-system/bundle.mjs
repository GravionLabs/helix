// components/bundle.css and the component folders of the Design System (#528): the resolved `--h-*` tokens
// (light, and `[data-theme="dark"]`, which the preview frame sets), the preset's extra CSS (projects/tokens core-css), the base CSS and
// the real structural CSS of every previewed component, with `dt('x.y')` resolved to `var(--h-x-y)` the way
// the styling engine does. Run: node scripts/design-system/bundle.mjs [outDir]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { coreCss } from '../../projects/tokens/src/core-css.ts';
import { helixTokens } from '../../projects/tokens/src/index.ts';
import { resolveTokens } from '../tokens/resolve.mjs';
import { MARKER_CLASSES, PREVIEWS, classesOf } from './previews.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const DARK_SELECTOR = '[data-theme="dark"]';

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

/** `dt('button.primary.color')` → `var(--h-button-primary-color)`; `dt('a.b', '50%')` → `var(--h-a-b, 50%)`. */
export function resolveDt(css) {
  return css.replace(/dt\('([^']+)'(?:,\s*'([^']*)')?\)/g, (_, token, fallback) => {
    const name = `--h-${token.split('.').map(kebab).join('-')}`;
    return fallback == null ? `var(${name})` : `var(${name}, ${fallback})`;
  });
}

/** The CSS string that projects/core/<dir>/style/<dir>.css.ts exports. */
export function readStyle(dir) {
  const file = path.join(ROOT, 'projects/core', dir, 'style', `${dir}.css.ts`);
  const source = fs.readFileSync(file, 'utf8');
  const match = /export const style = \/\*css\*\/ `([\s\S]*)`;?\s*$/.exec(source);
  if (!match) throw new Error(`${file}: no \`export const style = /*css*/ \`…\`\``);
  if (match[1].includes('${')) throw new Error(`${file}: the CSS uses a template expression`);
  return resolveDt(match[1]);
}

const dedent = (css) => css.replace(/^ {4}/gm, '').trim();

// The layout helpers of the preview documents (not part of the components).
const PREVIEW_CSS = `body{margin:0;padding:20px 24px;background:var(--content-bg);color:var(--text);font-family:var(--font-sans),system-ui,sans-serif;font-size:14px;line-height:1.4}
.row{display:flex;flex-wrap:wrap;gap:8px;align-items:center;margin-bottom:12px}
.stack{display:flex;flex-direction:column;gap:12px}
.field{display:flex;flex-direction:column;gap:6px;font-weight:500}
.field>input,.field>textarea{width:100%;box-sizing:border-box}
.inline{display:inline-flex;align-items:center;gap:8px;margin-right:16px}
.msg{color:var(--danger);font-weight:400}`;

export async function buildBundleCss() {
  const dirs = [...new Set(PREVIEWS.flatMap((p) => p.css))];
  const { css: tokens } = resolveTokens(helixTokens, { darkSelector: DARK_SELECTOR, components: dirs });
  const presetCss = coreCss;
  const parts = [
    '/* Helix Design System: generated by scripts/design-system/bundle.mjs from helixPreset (do not edit). */',
    '/* The application root is 14px, as in helix-shell. */\nhtml{font-size:14px}',
    `/* tokens: light on :root, dark under ${DARK_SELECTOR} */\n${tokens}`,
    `/* preset css */\n${dedent(presetCss)}`,
    `/* base */\n${dedent(readStyle('base'))}`,
    ...dirs.map((d) => `/* ${d} */\n${dedent(readStyle(d))}`),
  ];
  const css = `${parts.join('\n\n')}\n`;
  if (/<\/style/i.test(css)) throw new Error('bundle.css contains "</style"');
  return css;
}

const mdList = (items) => items.map((i) => `- ${i}`).join('\n');

export function readmeOf(p) {
  return `${p.summary}

## Guidelines

${mdList(p.guidelines)}

## Use

\`\`\`ts
import { ${p.name === 'InputText' ? 'InputText' : p.name} } from '${p.entry}';
\`\`\`

Selector: \`${p.selector}\`. The application provides \`provideHelix({ theme: { preset: helixPreset } })\`, the font (Inter) and, for dark mode, the \`app-dark\` class on \`<html>\`; the rendition here is static (Helix components are Angular, there is no runtime bundle).

${p.tokens}
`;
}

export function previewOf(p) {
  return `<!-- @dsCard group="${p.group}" height=${p.height} subtitle="${p.selector}" -->
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>${p.name}</title>
<style>
${PREVIEW_CSS}
</style>
</head>
<body>
${p.body.trim()}
</body>
</html>
`;
}

/** Every file of the components folder, `{ path under project/: text }`. */
export async function buildComponents() {
  const files = { 'components/bundle.css': await buildBundleCss() };
  for (const p of PREVIEWS) {
    files[`components/${p.name}/README.md`] = readmeOf(p);
    files[`components/${p.name}/preview.html`] = previewOf(p);
  }
  return files;
}

/** `h-*` classes the previews use that bundle.css never defines (as `.h-x`). */
export function undefinedClasses(files) {
  const css = files['components/bundle.css'];
  const missing = {};
  for (const p of PREVIEWS) {
    for (const c of classesOf(p.body)) {
      if (!/^h-/.test(c) || c === 'h-component' || MARKER_CLASSES.includes(c)) continue;
      const defined = new RegExp(`\\.${c.replace(/[-]/g, '\\-')}(?![\\w-])`).test(css);
      if (!defined) (missing[p.name] ??= []).push(c);
    }
  }
  return missing;
}

/** `var(--h-…)` the structural CSS uses without a fallback that no token block defines. */
export function undefinedVariables(css) {
  const defined = new Set([...css.matchAll(/(--h-[\w-]+)\s*:/g)].map((m) => m[1]));
  const used = new Set([...css.matchAll(/var\((--h-[\w-]+)\)/g)].map((m) => m[1]));
  return [...used].filter((v) => !defined.has(v)).sort();
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = path.resolve(ROOT, process.argv[2] ?? 'dist/design-system/project');
  const files = await buildComponents();
  for (const [rel, text] of Object.entries(files)) {
    const file = path.join(out, rel);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
  }
  const missingClasses = undefinedClasses(files);
  const missingVars = undefinedVariables(files['components/bundle.css']);
  console.log(`${path.relative(ROOT, out)}: ${PREVIEWS.length} components, bundle.css ${(files['components/bundle.css'].length / 1024).toFixed(0)} kB`);
  if (Object.keys(missingClasses).length) console.log('classes without CSS:', JSON.stringify(missingClasses));
  if (missingVars.length) console.log('variables without a token:', missingVars.join(', '));
}
